"""RELEASE-113: one-click PDF & natural-audio orchestration.

The script is editorially generated by Meta, automatically checked for structural
and provenance integrity, and NEVER represented as human-reviewed or field-verified.
No automatic retries. Charges arise only from the requested Generate action.
"""
import hashlib
import json
import os
from pathlib import Path
from urllib.parse import parse_qs, urlparse
import sys
import threading

import deliverables_112 as core

LOCK = threading.Lock()

def checked_script(ctx, obj):
    if not isinstance(obj, dict) or obj.get('source_trace_sha256') != ctx['sha'] or obj.get('language') != ctx['lang']:
        raise ValueError('Audio dialogue is not associated with this scientific session')
    if obj.get('verification') != 'automatic_structural_provenance_only' or obj.get('review_status') != 'not_human_reviewed':
        raise ValueError('Invalid automatic verification metadata')
    if obj.get('question') != ctx['question']:
        raise ValueError('Audio script question mismatch')
    turns = obj.get('turns')
    if ctx['lang'] == 'fr':
        sys.path.insert(0, str(core.ROOT / 'release_101_modules'))
        from universal_debate_100 import validate_turns, pack_chunks
        validate_turns(turns, ctx['question'], ctx['root'])
        pack_chunks(turns)
    else:
        import native_107
        native_107.validate_turns(turns)
        sys.path.insert(0, str(core.ROOT / 'release_101_modules'))
        from universal_debate_100 import pack_chunks
        pack_chunks(turns)
        all_text=' '.join(t['text'].lower() for t in turns)
        if not any(cue in all_text for cue in ('evidence','data','source','observation')):
            raise ValueError('Missing scientific evidence limitation in English dialogue')
    signature=hashlib.sha256(json.dumps(turns,sort_keys=True,ensure_ascii=False,separators=(',',':')).encode()).hexdigest()
    if obj.get('turns_sha256')!=signature:raise ValueError('Audio script integrity checksum mismatch')
    return turns

def script_path(ctx):
    return ctx['dest'] / ('automatic_dialogue_113_' + ctx['lang'] + '.json')

def load_script(ctx):
    path=script_path(ctx)
    if not path.is_file():return None
    return checked_script(ctx,core.json_read(path))

def construct_script(ctx, turns):
    obj={'schema':'terra-automatic-editorial/1.0','source_trace_sha256':ctx['sha'],
         'language':ctx['lang'],'question':ctx['question'], 'turns':turns,
         'review_status':'not_human_reviewed','verification':'automatic_structural_provenance_only',
         'editorial_adaptation_not_field_validation':True}
    obj['turns_sha256']=hashlib.sha256(json.dumps(turns,sort_keys=True,ensure_ascii=False,separators=(',',':')).encode()).hexdigest()
    checked_script(ctx,obj)
    return obj

def prepare_script(ctx):
    turns=load_script(ctx)
    if turns is not None:return turns
    # Reuse an already scientifically reviewed dialogue for this exact trace when present.
    try:
        already=core.approved(ctx)
    except (ValueError,KeyError,TypeError):
        already=None
    if already:
        obj=construct_script(ctx,already)
        ctx['dest'].mkdir(parents=True,exist_ok=True)
        script_path(ctx).write_text(json.dumps(obj,ensure_ascii=False,indent=2),encoding='utf8')
        return already
    if not os.environ.get('META_API_KEY'):raise ValueError('META_API_KEY not configured')
    import native_107
    if ctx['lang']=='en':
        draft=native_107.make_draft(ctx['result'],ctx['sha'],ctx['question'],native_107.call_meta)
        turns=draft['turns']
    else:
        sys.path.insert(0,str(core.ROOT/'release_101_modules'))
        import universal_debate_100 as engine
        def caller(model,instruction,payload,key):
            return native_107.call_meta(model,instruction,payload)
        draft=engine.meta_editor(ctx['root'],ctx['question'],caller,os.environ['META_API_KEY'])
        turns=draft.get('turns')
        engine.validate_turns(turns,ctx['question'],ctx['root'])
        engine.pack_chunks(turns)
        issues=engine.audit(ctx['root'],turns)
        if issues:
            raise ValueError('Automatic editorial checks need operator intervention: '+', '.join(map(str,issues))[:140])
    obj=construct_script(ctx,turns)
    ctx['dest'].mkdir(parents=True,exist_ok=True)
    # Write only AFTER validation; preserve any earlier valid script.
    target=script_path(ctx)
    temp=target.with_suffix('.tmp')
    temp.write_text(json.dumps(obj,ensure_ascii=False,indent=2),encoding='utf8')
    temp.replace(target)
    return turns

def find_audio(ctx,turns):
    return core.current_audio(ctx,turns) if turns else []

def status(ctx):
    pdf=core.pdf_files(ctx)
    try:turns=load_script(ctx)
    except (ValueError,TypeError,KeyError) as e:turns=None
    if turns is None:
        try:turns=core.approved(ctx)
        except (ValueError,KeyError,TypeError):turns=None
    audio=find_audio(ctx,turns)
    return {'language':ctx['lang'],'trace':ctx['trace'],'question':ctx['question'],
            'pdf':[{'name':p.name,'url':core.file_url(ctx,'pdf',p)} for p in pdf],
            'audio':[{'name':p.name,'url':'/api/release113/audio/'+ctx['lang']+'/'+ctx['trace']+'/'+p.name} for p in audio],
            'pdf_ready':bool(pdf),'audio_ready':bool(audio),
            'dialogue_prepared':bool(turns),'review_status':'not_human_reviewed' if turns else 'not_created'}

def generate(ctx,want_pdf,want_audio,allow_meta=False,allow_eleven=False):
    if not want_pdf and not want_audio:raise ValueError('Choose at least one deliverable')
    if not LOCK.acquire(blocking=False):raise ValueError('Another generation is already in progress')
    try:
        if want_pdf and not core.pdf_files(ctx):core.generate_pdf(ctx)
        if want_audio:
            turns=load_script(ctx)
            if turns is None:
                if not allow_meta:raise PermissionError('Meta editorial authorization required')
                turns=prepare_script(ctx)
            if not find_audio(ctx,turns):
                if not allow_eleven:raise PermissionError('ElevenLabs synthesis authorization required')
                sys.path.insert(0,str(core.ROOT/'release_101_modules'))
                if ctx['lang']=='fr':
                    import universal_debate_100 as engine
                    plan=engine.build_plan(ctx['path'],{'turns':turns,'mode':'automatic_editorial_not_human_reviewed'})
                    engine.render(plan,ctx['dest']/'audio')
                else:
                    from bilingual_102 import render_audio_en
                    render_audio_en({'turns_en':turns,'source_trace_sha256':ctx['sha']},ctx['dest']/'audio')
            if not find_audio(ctx,turns):raise ValueError('Audio generation did not pass integrity checks')
        return status(ctx)
    finally:LOCK.release()

def respond(h,code,obj):return core.respond(h,code,obj)

def handle_post(h):
    try:
        size=int(h.headers.get('Content-Length','0'))
        if size<1 or size>16000:raise ValueError('Invalid request length')
        obj=json.loads(h.rfile.read(size))
        if obj.get('action')!='generate':raise ValueError('Unsupported action')
        ctx=core.context(obj.get('trace'),obj.get('language'))
        return respond(h,200,generate(ctx,obj.get('pdf') is True,obj.get('audio') is True,
                                    obj.get('authorize_meta_charge') is True,obj.get('authorize_eleven_charge') is True))
    except PermissionError as e:return respond(h,403,{'error':str(e)})
    except (ValueError,KeyError,TypeError) as e:return respond(h,409,{'error':str(e)[:240]})
    except Exception as e:
        print('RELEASE-113 error:',type(e).__name__,str(e)[:200],flush=True)
        return respond(h,500,{'error':'Generation failed. Saved valid files remain available; no automatic paid retry.'})

def handle_get(h):
    from urllib.parse import unquote
    uri=urlparse(h.path)
    if uri.path=='/api/release113/status':
        try:
            args=parse_qs(uri.query)
            ctx=core.context(args.get('trace',[''])[0],args.get('language',[''])[0])
            return respond(h,200,status(ctx))
        except (ValueError,KeyError,TypeError) as e:return respond(h,409,{'error':str(e)[:200]})
    if uri.path.startswith('/api/release113/audio/'):
        parts=[unquote(x) for x in uri.path[len('/api/release113/audio/'):].split('/')]
        if len(parts)!=3:return h.send_error(404)
        lang,trace,name=parts
        try:
            ctx=core.context(trace,lang)
            turns=load_script(ctx)
            if not turns:return h.send_error(404)
            file=next((p for p in find_audio(ctx,turns) if p.name==name),None)
            if file is None:return h.send_error(404)
            return core.stream(h,file,'audio')
        except (ValueError,KeyError,TypeError,OSError):return h.send_error(404)
    return h.send_error(404)
