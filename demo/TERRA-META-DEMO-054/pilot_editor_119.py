def moderator_issues(turns):
    issues=[]
    if not isinstance(turns,list):return ['missing turns']
    for i,turn in enumerate(turns):
        if not isinstance(turn,dict):return [f'invalid turn {i}']
        if turn.get('role') != 'moderator':continue
        message=str(turn.get('text',''))
        for pattern,reason in DISALLOWED:
            if re.search(pattern,message,flags=re.IGNORECASE):
                issues.append(f'moderator turn {i+1}: {reason}')
                break
    return issues


def segment_long_turns_119b(turns, cap=540):
    # Exact-word, zero-generation segmentation of overlong editorial turns.
    # Preserves all text and speaker attribution; never splits within a sentence.
    # Refuses rather than silently shortening text or bypassing 7..13 turn limit.
    import re
    if not isinstance(turns,list):return turns
    result=[]
    for turn in turns:
        if not isinstance(turn,dict) or not isinstance(turn.get('text'),str):
            result.append(turn);continue
        original=turn['text'].strip()
        if len(original)<=550:
            result.append(turn);continue
        # Break only at punctuation followed by a space. Each segment is
        # formed by joining exact, intact sentences; no new statements.
        pieces=re.split(r'(?<=[.!?])\s+(?=\S)',original)
        segments=[];current=''
        for piece in pieces:
            if len(piece)>cap:
                raise ValueError('119B UNSPLITTABLE_LONG_SENTENCE: no audio attempted; editorial draft needs a shorter sentence')
            trial=(current+' '+piece).strip() if current else piece
            if len(trial)>cap and current:
                segments.append(current);current=piece
            else:current=trial
        if current:segments.append(current)
        if any(len(t)<15 or len(t)>550 for t in segments):
            raise ValueError('119B INVALID_SEGMENT_LENGTH: no audio attempted')
        # Make sure only whitespace at sentence boundaries was normalized.
        if re.sub(r'\s+',' ', ' '.join(segments)).strip()!=re.sub(r'\s+',' ',original).strip():
            raise ValueError('119B SEGMENT_FIDELITY_FAILED: no audio attempted')
        result.extend({**turn,'text':segment} for segment in segments)
    if len(result)>13:
        raise ValueError('119B TOO_MANY_TURNS_AFTER_SPLIT: no audio attempted; need shorter editorial draft')
    return result

def prepare_pilot(ctx, lang, *, authorize_editorial=False):
    """Return a compliant script, or create one by precisely one Meta editorial call.

    The existing script is preserved until a replacement has been generated and
    validated successfully. Failed generations never overwrite a good/old script.
    """
    import auto_113
    import native_107
    path=auto_113.script_path(ctx)
    existing=auto_113.load_script(ctx)
    if existing is not None and not moderator_issues(existing):
        print('REUSE VALID EDITORIAL SCRIPT (no Meta editorial call)')
        return existing
    if not authorize_editorial:
        raise PermissionError('An editorial Meta call is required; add --authorize-meta-editorial')
    if not os.environ.get('META_API_KEY'):
        raise ValueError('META_API_KEY missing; no paid call attempted')
    if lang=='en':
        def caller(model,instruction,payload):
            return native_107.call_meta(model,instruction+'\n'+EN_POLICY,payload)
        draft=native_107.make_draft(ctx['result'],ctx['sha'],ctx['question'],caller)
        turns=draft['turns']
    elif lang=='fr':
        root=ctx['root']
        sys.path.insert(0,str(Path(ctx['path']).parents[0]))
        sys.path.insert(0,str(auto_113.core.ROOT/'release_101_modules'))
        import universal_debate_100 as engine
        def caller(model,instruction,payload,key):
            return native_107.call_meta(model,instruction+'\n'+FR_POLICY,payload)
        draft=engine.meta_editor(root,ctx['question'],caller,os.environ['META_API_KEY'])
        turns=segment_long_turns_119b(draft['turns'])
        engine.validate_turns(turns,ctx['question'],root)
        engine.pack_chunks(turns)
        issues=engine.audit(root,turns)
        # RELEASE-119A: FINAL-100 expected audible disclosure in the dialogue.
        # RELEASE-119 places disclosure in structured metadata / branded reports;
        # the moderator must not speak production metadata. Keep every other
        # scientific and structural audit finding as a blocking condition.
        issues=[issue for issue in issues if issue != 'MISSING_EDITORIAL_DISCLOSURE']
        if issues:raise ValueError('Scientific editorial audit failed; no audio attempted: '+str(issues)[:160])
    else:raise ValueError('Unsupported language')
    issues=moderator_issues(turns)
    if issues:raise ValueError('Moderator editorial policy failed; no ElevenLabs call: '+', '.join(issues))
    new=auto_113.construct_script(ctx,turns)
    path.parent.mkdir(parents=True,exist_ok=True)
    # Preserve old script even if replacement is rejected in subsequent downstream checks.
    if path.exists():
        i=0
        while True:
            i+=1
            backup=path.with_name(path.stem+f'.before-119-{i:02d}.json')
            if not backup.exists():break
        backup.write_bytes(path.read_bytes())
    tmp=path.with_suffix('.119.tmp')
    tmp.write_text(json.dumps(new,ensure_ascii=False,indent=2),encoding='utf8')
    tmp.replace(path)
    print('NEW MODERATOR-COMPLIANT SCRIPT SAVED: ',path)
    return turns

def synthesize(root,pilot,lang,allow_meta=False,allow_eleven=False):
    """Use verified existing trace; no reasoning re-run; guarded editorial + audio."""
    import pilot_record_116b as base
    rec,work,path,obj=base.verify_index(root,pilot,lang)
    if not allow_meta or not allow_eleven:
        raise PermissionError('Explicit --authorize-meta-editorial and --authorize-eleven required')
    sys.path.insert(0,str(root))
    import deliverables_112 as core
    import auto_113
    ctx=core.context(rec['trace'],lang)
    if ctx['sha']!=rec['sha256']:raise ValueError('Meta trace fingerprint changed')
    turns=prepare_pilot(ctx,lang,authorize_editorial=allow_meta)
    issues=moderator_issues(turns)
    if issues:raise ValueError('Moderator text rejected before ElevenLabs')
    answer=auto_113.generate(ctx,False,True,allow_meta=True,allow_eleven=allow_eleven)
    if not answer.get('audio_ready'):raise ValueError('Audio not verified; no automatic retry')
    print('POLICY-119 AUDIO VERIFIED:',pilot,lang,len(answer['audio']),'segments')
    return answer

def published_audio_allowed(root,pilot,lang,manifest):
    """Fail closed if a published MP3 no longer matches the current, clean dialogue.

    This makes outdated moderator narration invisible in Jury Demo without deleting
    previously paid audio files or mutating any historic scientific records.
    """
    try:
        import deliverables_112 as core
        import auto_113
        ctx=core.context(manifest['source_trace'],lang)
        turns=auto_113.load_script(ctx)
        if not turns or moderator_issues(turns):return False
        actual=core.current_audio(ctx,turns)
        recorded=manifest.get('segments',[])
        if not actual or len(actual)!=len(recorded):return False
        for i,(file,entry) in enumerate(zip(actual,recorded),1):
            if entry.get('sequence')!=i:return False
            if hashlib.sha256(file.read_bytes()).hexdigest()!=entry.get('sha256'):return False
        return True
    except (ValueError,KeyError,TypeError,OSError,ImportError,AttributeError):
        return False
